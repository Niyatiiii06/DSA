
# Arrays Basics — Python

arr = [10, 20, 30, 40, 50]

# 1. Access elements using indices
print(arr[0])
print(arr[2])

# 2. Update an element
arr[1] = 99
print(arr)

# 3. Find the length
print(len(arr))

# 4. Traverse using indices
for i in range(len(arr)):
    print(arr[i])

# 5. Traverse directly through values
for num in arr:
    print(num)
